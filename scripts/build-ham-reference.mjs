// Generates the static reference data used by ham-map.html:
//   data/dxcc-entities.js  - active DXCC entities (k0swe/dxcc-json, Apache-2.0)
//   data/cq-zones.js       - simplified CQ zone polygons (HB9HIL/hamradio-zones-geojson, MIT)
//   data/itu-zones.js      - simplified ITU zone polygons (HB9HIL/hamradio-zones-geojson, MIT)
//
// Usage (one-off, the output files are committed):
//   npm install --no-save mapshaper@0.6 d3-geo@3
//   node scripts/build-ham-reference.mjs
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import mapshaper from "mapshaper";
import { geoArea } from "d3-geo";

const OUT_DIR = path.resolve(process.argv[2] || path.join(process.cwd(), "data"));
const DXCC_URL = "https://raw.githubusercontent.com/k0swe/dxcc-json/main/dxcc.json";
const ZONES_BASE = "https://raw.githubusercontent.com/HB9HIL/hamradio-zones-geojson/main";
const SIMPLIFY = "4%";
const DENSIFY_STEP_DEG = 2;

async function main() {
  await buildDxcc();
  await buildZones("cqzones.geojson", "cq-zones.js", "__HAM_CQ_ZONES__", "cq_zone_number", "cq_zone_name", "cq_zone_name_loc");
  await buildZones("ituzones.geojson", "itu-zones.js", "__HAM_ITU_ZONES__", "itu_zone_number", "itu_zone_name", "itu_zone_name_loc");
}

async function buildDxcc() {
  const res = await fetch(DXCC_URL);
  if (!res.ok) {
    throw new Error(`HTTP ${res.status} for ${DXCC_URL}`);
  }
  const { dxcc } = await res.json();
  // [entityCode, name, prefixes, continent, cqZones, ituZones]
  const rows = dxcc
    .filter((entity) => !entity.deleted)
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((entity) => [
      entity.entityCode,
      entity.name,
      entity.prefix,
      entity.continent[0] || "",
      entity.cq,
      entity.itu
    ]);

  const body = rows.map((row) => `  ${JSON.stringify(row)}`).join(",\n");
  const js = `// Active DXCC entities: [entityCode, name, prefixes, continent, cqZones, ituZones]\n// Source: https://github.com/k0swe/dxcc-json (Apache-2.0), generated by scripts/build-ham-reference.mjs\nwindow.__HAM_DXCC__ = [\n${body}\n];\n`;
  await fs.writeFile(path.join(OUT_DIR, "dxcc-entities.js"), js, "utf8");
  console.log(`dxcc-entities.js: ${rows.length} entities`);
}

async function buildZones(sourceFile, outFile, globalName, numberKey, nameKey, locKey) {
  const res = await fetch(`${ZONES_BASE}/${sourceFile}`);
  if (!res.ok) {
    throw new Error(`HTTP ${res.status} for ${sourceFile}`);
  }

  const tmpDir = await fs.mkdtemp(path.join(os.tmpdir(), "ham-zones-"));
  const input = path.join(tmpDir, "in.geojson");
  const output = path.join(tmpDir, "out.geojson");
  await fs.writeFile(input, await res.text(), "utf8");
  await mapshaper.runCommands(`-i "${input}" -simplify ${SIMPLIFY} keep-shapes -o "${output}" format=geojson precision=0.01`);
  const simplified = JSON.parse(await fs.readFile(output, "utf8"));
  await fs.rm(tmpDir, { recursive: true, force: true });

  let vertices = 0;
  const features = simplified.features.map((feature) => {
    const polygons = feature.geometry.type === "MultiPolygon"
      ? feature.geometry.coordinates
      : [feature.geometry.coordinates];

    const fixed = polygons.map((rings) => {
      // Zone edges are mostly parallels and meridians; densify so they stay
      // straight-on-the-map instead of bending into great-circle arcs.
      let polygon = rings.map(densifyRing);
      // d3-geo expects clockwise exterior rings; flip anything wound the GeoJSON way.
      if (geoArea({ type: "Polygon", coordinates: polygon }) > 2 * Math.PI) {
        polygon = polygon.map((ring) => [...ring].reverse());
      }
      vertices += polygon.reduce((sum, ring) => sum + ring.length, 0);
      return polygon;
    });

    const loc = feature.properties[locKey] || [];
    return {
      type: "Feature",
      properties: {
        zone: feature.properties[numberKey],
        name: cleanZoneName(feature.properties[nameKey]),
        label: [round(loc[1]), round(loc[0])]
      },
      geometry: fixed.length === 1
        ? { type: "Polygon", coordinates: fixed[0] }
        : { type: "MultiPolygon", coordinates: fixed }
    };
  }).sort((a, b) => a.properties.zone - b.properties.zone);

  const collection = { type: "FeatureCollection", features };
  const js = `// Source: https://github.com/HB9HIL/hamradio-zones-geojson (MIT), simplified by scripts/build-ham-reference.mjs\nwindow.${globalName} = ${JSON.stringify(collection)};\n`;
  await fs.writeFile(path.join(OUT_DIR, outFile), js, "utf8");
  console.log(`${outFile}: ${features.length} zones, ${vertices} vertices, ${(js.length / 1024).toFixed(0)} KB`);
}

function densifyRing(ring) {
  const out = [];
  for (let i = 0; i < ring.length; i += 1) {
    const [lon1, lat1] = ring[i];
    out.push([round(lon1), round(lat1)]);
    const next = ring[i + 1];
    if (!next) {
      continue;
    }
    const [lon2, lat2] = next;
    const steps = Math.floor(Math.max(Math.abs(lon2 - lon1), Math.abs(lat2 - lat1)) / DENSIFY_STEP_DEG);
    for (let s = 1; s < steps; s += 1) {
      const t = s / steps;
      out.push([round(lon1 + (lon2 - lon1) * t), round(lat1 + (lat2 - lat1) * t)]);
    }
  }
  return out;
}

function cleanZoneName(raw) {
  // ITU names carry encoded prefix lists ("!!:PY:**Brazil, south of 16.5º S#..."); keep readable text only.
  return String(raw || "")
    .split("#")
    .map((part) => part.replace(/^[!]*:?[^:]*:\**/, "").trim())
    .filter(Boolean)
    .join("; ");
}

function round(value) {
  return Math.round(Number(value) * 100) / 100;
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
